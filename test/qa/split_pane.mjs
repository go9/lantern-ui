// BASE=http://127.0.0.1:4018 CHROME_PATH=/usr/bin/chromium node test/qa/split_pane.mjs
import assert from "node:assert/strict"
import { mkdir } from "node:fs/promises"
import puppeteer from "puppeteer-core"
const shots = process.env.QA_SHOTS || "/tmp/lantern-split-pane"
await mkdir(shots, { recursive: true })
const browser = await puppeteer.launch({ executablePath: process.env.CHROME_PATH || "/usr/bin/chromium", headless: true, args: ["--no-sandbox"] })
try {
  const page = await browser.newPage()
  const errors = []
  page.on("pageerror", error => errors.push(error.message))
  await page.setViewport({ width: 1440, height: 800 })
  await page.goto(`${process.env.BASE || "http://127.0.0.1:4018"}/split_pane`)
  await page.waitForSelector(".phx-connected")
  const edge = "#suggestions-separator"
  const value = () => page.$eval(edge, el => Number(el.getAttribute("aria-valuenow")))
  const width = () => page.$eval("#suggestions-primary", el => el.getBoundingClientRect().width)
  await page.focus(edge)
  const initial = await value()
  const initialWidth = await width()
  await page.keyboard.press("ArrowRight")
  assert.equal(await value(), initial + 1)
  assert.ok(await width() > initialWidth)
  const box = await page.$eval(edge, el => { const r = el.getBoundingClientRect(); return { x: r.x + r.width / 2, y: r.y + r.height / 2 } })
  await page.mouse.move(box.x, box.y)
  await page.mouse.down()
  await page.mouse.move(box.x + 100, box.y)
  await page.mouse.up()
  const dragged = await value()
  assert.ok(dragged > initial + 1)
  await page.click('a[phx-click="detail"]')
  await page.waitForSelector('[data-mobile-pane="secondary"]')
  assert.equal(await value(), dragged, "LiveView patch preserves resized width")
  await page.reload()
  await page.waitForSelector(".phx-connected")
  assert.equal(await value(), dragged, "reload restores width")
  await page.screenshot({ path: `${shots}/desktop.png`, fullPage: true })
  await page.emulateMediaFeatures([{ name: "prefers-reduced-motion", value: "reduce" }])
  await page.setViewport({ width: 390, height: 844 })
  assert.equal(await page.$eval("#suggestions-secondary", el => getComputedStyle(el).display), "none")
  assert.equal(await page.$eval(edge, el => getComputedStyle(el).display), "none")
  await page.screenshot({ path: `${shots}/mobile-list.png`, fullPage: true })
  await page.click('a[phx-click="detail"]')
  await page.waitForSelector('[data-mobile-pane="secondary"]')
  assert.equal(await page.$eval("#suggestions-primary", el => getComputedStyle(el).display), "none")
  assert.ok(await page.$eval("#suggestions-secondary", el => el.getBoundingClientRect().width) > 0)
  await page.screenshot({ path: `${shots}/mobile-detail.png`, fullPage: true })
  await page.click('button[phx-click="back"]')
  await page.waitForSelector('[data-mobile-pane="primary"]')
  await page.setViewport({ width: 1440, height: 800 })
  await page.evaluate(() => { document.documentElement.dir = "rtl"; document.documentElement.classList.add("dark") })
  await page.focus(edge)
  await page.keyboard.press("ArrowLeft")
  assert.equal(await value(), Math.round((dragged + 1) * 100) / 100)
  await page.screenshot({ path: `${shots}/rtl-dark.png`, fullPage: true })
  assert.deepEqual(errors, [])
  console.log("split_pane: desktop drag/keyboard, patch, persistence, mobile Back, reduced-motion and RTL passed")
} finally { await browser.close() }
